const PLURAL_OVERRIDE: Record<string, string> = { тарих: 'тарихтар' }
const BACK = 'аоұыяю'
const FRONT = 'әөүіеи'

// Көптік жалғау: дауыстыдан кейін және р, у, й-дан кейін -лар/-лер; л, м, н, ң, д, ж, з-дан кейін -дар/-дер; қалғанында -тар/-тер
export function pluralOf(word: string): string {
  const w = word.toLowerCase()
  if (PLURAL_OVERRIDE[w]) return PLURAL_OVERRIDE[w]
  let back = true
  for (let i = w.length - 1; i >= 0; i--) {
    if (BACK.includes(w[i])) break
    if (FRONT.includes(w[i])) {
      back = false
      break
    }
  }
  const last = w[w.length - 1]
  let c = 'л'
  if ('аәоөұүыіеиуюяэйр'.includes(last)) c = 'л'
  else if ('лмнңджз'.includes(last)) c = 'д'
  else c = 'т'
  return w + c + (back ? 'ар' : 'ер')
}

let cache: DictEntry[] | null = null

export function allEntries(): DictEntry[] {
  if (cache) return cache
  const map = new Map<string, DictEntry>()
  for (const line of RAW.trim().split('\n')) {
    const [kk, ru, pos, level, exKk, exRu] = line.split('|')
    const p = pos as Pos
    map.set(kk, { kk, ru, pos: p, level, exKk, exRu, plural: p === 'N' ? pluralOf(kk) : undefined })
  }
  for (const w of collectWords()) {
    const key = w.kk.toLowerCase()
    const level = w.lessonId.split('-')[0].toUpperCase()
    const base = map.get(key)
    if (base) {
      base.lessonId = w.lessonId
      base.lessonTitle = w.lessonTitle
      continue
    }
    map.set(key, { kk: w.kk, ru: w.ru, level, lessonId: w.lessonId, lessonTitle: w.lessonTitle, note: w.note })
  }
  cache = Array.from(map.values())
  return cache
}
