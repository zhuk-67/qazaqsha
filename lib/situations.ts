function ch(prompt: string, right: string, wrongs: string[], explain: string): GrammarQuestion {
  let h = 0
  for (let i = 0; i < prompt.length; i++) h = (h * 31 + prompt.charCodeAt(i)) >>> 0
  const pos = h % (wrongs.length + 1)
  const options = [...wrongs]
  options.splice(pos, 0, right)
  return { kind: 'choice', prompt, options, answer: pos, explain }
}

function fill(prompt: string, accepted: string[], explain: string, hint = ''): GrammarQuestion {
  return { kind: 'fill', prompt, accepted: accepted.map((a) => a.toLowerCase()), explain, hint }
}

